// Command oracle runs every conformance case through Go's text/template and
// records what the reference implementation does. The result is written as
// MoonBit source so the test suite needs no file access at run time.
//
// Usage:
//
//	cd tools/oracle && go run .
//
// Input:  cases/*.jsonl  one case per line: ["template", data]
// Output: ../../conformance_data_test.mbt
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
)

type result struct {
	file string
	line int
	tmpl string
	data string
	kind string // "ok", "parse" or "exec"
	out  string
}

// convert turns decoded JSON into the Go values a template would normally
// see: integers become int, other numbers float64.
func convert(v any) any {
	switch x := v.(type) {
	case json.Number:
		s := x.String()
		if !strings.ContainsAny(s, ".eE") {
			if i, err := x.Int64(); err == nil {
				return int(i)
			}
		}
		f, _ := x.Float64()
		return f
	case []any:
		for i := range x {
			x[i] = convert(x[i])
		}
		return x
	case map[string]any:
		for k := range x {
			x[k] = convert(x[k])
		}
		return x
	}
	return v
}

func run(tmpl string, data any) (kind, out string) {
	defer func() {
		if r := recover(); r != nil {
			kind, out = "exec", ""
		}
	}()
	t, err := template.New("t").Parse(tmpl)
	if err != nil {
		return "parse", ""
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return "exec", ""
	}
	return "ok", buf.String()
}

// quote writes a MoonBit string literal.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteString(`\t`)
		case r == '\r':
			b.WriteString(`\r`)
		case r < 0x20 || r == 0x7f || r > 0x7e:
			fmt.Fprintf(&b, `\u{%x}`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func main() {
	files, err := filepath.Glob("cases/*.jsonl")
	if err != nil || len(files) == 0 {
		fmt.Fprintln(os.Stderr, "no case files found; run from tools/oracle")
		os.Exit(1)
	}
	sort.Strings(files)
	var results []result
	seen := map[string]bool{}
	for _, file := range files {
		f, err := os.Open(file)
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		sc := bufio.NewScanner(f)
		sc.Buffer(make([]byte, 1<<20), 1<<20)
		n := 0
		for sc.Scan() {
			n++
			line := strings.TrimSpace(sc.Text())
			if line == "" || strings.HasPrefix(line, "#") {
				continue
			}
			var pair []json.RawMessage
			if err := json.Unmarshal([]byte(line), &pair); err != nil || len(pair) != 2 {
				fmt.Fprintf(os.Stderr, "%s:%d: want [\"template\", data]\n", file, n)
				os.Exit(1)
			}
			var tmpl string
			if err := json.Unmarshal(pair[0], &tmpl); err != nil {
				fmt.Fprintf(os.Stderr, "%s:%d: template must be a string\n", file, n)
				os.Exit(1)
			}
			dec := json.NewDecoder(bytes.NewReader(pair[1]))
			dec.UseNumber()
			var raw any
			if err := dec.Decode(&raw); err != nil {
				fmt.Fprintf(os.Stderr, "%s:%d: bad data: %v\n", file, n, err)
				os.Exit(1)
			}
			key := tmpl + "\x00" + string(pair[1])
			if seen[key] {
				fmt.Fprintf(os.Stderr, "%s:%d: duplicate case\n", file, n)
				os.Exit(1)
			}
			seen[key] = true
			kind, out := run(tmpl, convert(raw))
			results = append(results, result{filepath.Base(file), n, tmpl, string(pair[1]), kind, out})
		}
		f.Close()
	}

	var b strings.Builder
	b.WriteString("// Generated by tools/oracle from tools/oracle/cases/*.jsonl. DO NOT EDIT.\n")
	b.WriteString("// Each entry: (source location, template, data as JSON, what Go does, Go's output).\n\n")
	b.WriteString("///|\n")
	b.WriteString("let conformance_cases : Array[(String, String, String, String, String)] = [\n")
	counts := map[string]int{}
	for _, r := range results {
		counts[r.kind]++
		fmt.Fprintf(&b, "  (%s, %s, %s, %s, %s),\n",
			quote(fmt.Sprintf("%s:%d", r.file, r.line)), quote(r.tmpl), quote(r.data), quote(r.kind), quote(r.out))
	}
	b.WriteString("]\n")
	if err := os.WriteFile("../../conformance_data_test.mbt", []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("%d cases: %d ok, %d parse errors, %d exec errors\n",
		len(results), counts["ok"], counts["parse"], counts["exec"])
}
